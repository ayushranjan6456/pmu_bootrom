#!/usr/bin/env python3
"""Generate src/floor_table.h: FLOOR[cp][sub] = round(F x median of the clean training boots).

Usage: python3 scripts/calibrate_floor.py [clean_csv] [F]
Defaults: data/cal_clean.csv, F = 0.45.
Calibrate from a clean set collected with the same firmware binary that will be validated.
"""
import sys
import numpy as np
import pandas as pd

path = sys.argv[1] if len(sys.argv) > 1 else "data/cal_clean.csv"
F = float(sys.argv[2]) if len(sys.argv) > 2 else 0.45
df = pd.read_csv(path).sort_values(["boot_id", "cp"])
assert (df.cp.values.reshape(-1, 8) == np.arange(8)).all(), "need 8 checkpoints per boot"
a = df[["sub_a", "sub_b", "sub_c"]].to_numpy(float).reshape(-1, 8, 3)
med = np.median(a, axis=0)
floor = np.floor(F * med).astype(int)
floor[0] = 0
assert floor.max() < 65536

rows = [f"    {{{floor[cp, 0]}, {floor[cp, 1]}, {floor[cp, 2]}}},  /* CP{cp} */" for cp in range(8)]
text = (f"/* Generated by scripts/calibrate_floor.py from {path} ({a.shape[0]} boots), F = {F}. Do not edit. */\n"
        + "\n".join(rows) + "\n")
open("src/floor_table.h", "w").write(text)
print(text)
print(f"lowest clean sub-stage / median over CP1-7: {(a[:, 1:, :] / med[1:]).min():.2f}  (F must stay below this)")
