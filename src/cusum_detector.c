/*
 * cusum_detector.c
 * ================
 * Firmware implementation of CUSUM fault injection detector.
 *
 * Algorithm:
 *   1. Compute Mahalanobis distance: MD = sqrt((x-mu)' * Σ⁻¹ * (x-mu))
 *   2. Update CUSUM statistic: S = max(0, S + MD - k)
 *   3. Check alarm condition: if S > H, then attack detected
 *
 * Implementation Notes:
 *   - Fixed-point Q16.16 arithmetic (no FPU required)
 *   - Model parameters embedded at compile time
 *   - Integer sqrt to avoid 64-bit division
 *   - Footprint and latency: not yet measured (see STATUS.md)
 */

#include "cusum_detector.h"

/* ──────────────────────────────────────────────────────────────────────
 * EMBEDDED MODEL PARAMETERS
 * ──────────────────────────────────────────────────────────────────────
 * Generated by scripts/calibrate_firmware.py from data/nominal_boots.csv.
 * This constant is the single record of the model values; regenerate it
 * after any change to boot-stage timing. The detector runs once per boot,
 * so the script sets k_slack = 0 and H = 1.25 x max clean MD (one-shot
 * threshold on Mahalanobis distance).
 */
const cusum_model_t CUSUM_MODEL = {
    /* Mean vector [sub_a, sub_b, sub_c] - Calibrated from v0.3 data */
    .mu = {
        FLOAT_TO_FIXED(695.437500),    /* mu[0] = sub_a */
        FLOAT_TO_FIXED(582.651210),    /* mu[1] = sub_b */
        FLOAT_TO_FIXED(501.770161),    /* mu[2] = sub_c */
    },

    /* Inverse covariance matrix (symmetric) - Calibrated from v0.3 data */
    .cov_inv = {
        {FLOAT_TO_FIXED(0.001665), FLOAT_TO_FIXED(-0.000931), FLOAT_TO_FIXED(-0.000770)},
        {FLOAT_TO_FIXED(-0.000931), FLOAT_TO_FIXED(0.002065), FLOAT_TO_FIXED(-0.001257)},
        {FLOAT_TO_FIXED(-0.000770), FLOAT_TO_FIXED(-0.001257), FLOAT_TO_FIXED(0.002595)},
    },

    /* CUSUM parameters */
    .k_slack = FLOAT_TO_FIXED(0.000000),   /* one-shot test: S = MD */
    .H       = FLOAT_TO_FIXED(10.836719),  /* 1.25 x max clean MD */
};

/* ──────────────────────────────────────────────────────────────────────
 * FIXED-POINT SQUARE ROOT
 * ──────────────────────────────────────────────────────────────────────
 * sqrt of a Q16.16 value x is isqrt(x << 16) in Q16.16. Done in 64-bit with
 * the bit-by-bit method (no division), so the fractional part of the result
 * is kept (truncating to an integer let MD 15.5-16.0 slip under the threshold).
 */
fixed_t fixed_sqrt(fixed_t x) {
    if (x <= 0) return 0;

    uint64_t n = (uint64_t)(uint32_t)x << 16;
    uint64_t result = 0;
    uint64_t bit = 1ULL << 46;  /* Highest power of 4 <= 2^47 */

    while (bit > n) {
        bit >>= 2;
    }

    while (bit != 0) {
        if (n >= result + bit) {
            n -= result + bit;
            result = (result >> 1) + bit;
        } else {
            result >>= 1;
        }
        bit >>= 2;
    }

    return (fixed_t)result;
}

/* ──────────────────────────────────────────────────────────────────────
 * MAHALANOBIS DISTANCE
 * ──────────────────────────────────────────────────────────────────────
 * Computes: MD = sqrt((x-mu)' * Σ⁻¹ * (x-mu))
 *
 * Steps:
 *   1. delta = x - mu  (difference vector)
 *   2. y = Σ⁻¹ * delta  (matrix-vector multiply)
 *   3. q = delta' * y   (dot product, gives squared distance)
 *   4. MD = sqrt(q)
 */
fixed_t mahalanobis_distance(const uint32_t obs[3],
                              const cusum_model_t *model) {
    /* Step 1: Compute delta = obs - mu. Observations that do not fit in Q16.16
     * (including a wrapped SysTick difference near 2^32) are clamped to the
     * largest representable value, so they read as a huge distance. */
    fixed_t delta[3];
    for (int i = 0; i < 3; i++) {
        uint32_t o = obs[i] > 32767U ? 32767U : obs[i];
        delta[i] = int_to_fixed((int32_t)o) - model->mu[i];
    }

    /* Step 2: Compute y = cov_inv * delta (matrix-vector multiply) */
    fixed_t y[3];
    for (int i = 0; i < 3; i++) {
        int64_t sum = 0;
        for (int j = 0; j < 3; j++) {
            /* Multiply and accumulate in Q32.32, then shift to Q16.16 */
            sum += ((int64_t)model->cov_inv[i][j] * (int64_t)delta[j]);
        }
        y[i] = (fixed_t)(sum >> 16);  /* Convert Q32.32 to Q16.16 */
    }

    /* Step 3: Compute q = delta' * y (dot product, squared distance) */
    int64_t q_int64 = 0;
    for (int i = 0; i < 3; i++) {
        q_int64 += ((int64_t)delta[i] * (int64_t)y[i]);
    }

    /* q is a positive-definite quadratic form, so it is never negative; a tiny
     * negative value can only come from rounding. A value that does not fit in
     * Q16.16 (q >= 32768, distance >= 181) must saturate at the maximum: casting
     * it down would wrap, and the old clamp-to-zero turned it into "no alarm". */
    int64_t q64 = q_int64 >> 16;  /* Q32.32 to Q16.16 */
    fixed_t q_fixed;
    if (q64 < 0) {
        q_fixed = 0;
    } else if (q64 > (int64_t)INT32_MAX) {
        q_fixed = INT32_MAX;
    } else {
        q_fixed = (fixed_t)q64;
    }

    /* Step 4: Return sqrt(q) */
    return fixed_sqrt(q_fixed);
}

/* ──────────────────────────────────────────────────────────────────────
 * CUSUM INITIALIZATION
 * ──────────────────────────────────────────────────────────────────────
 */
void cusum_init(cusum_state_t *state) {
    state->S = 0;
    state->alarm = 0;
    state->alarm_cp = 0;
}

/* ──────────────────────────────────────────────────────────────────────
 * CUSUM UPDATE
 * ──────────────────────────────────────────────────────────────────────
 * CUSUM algorithm:
 *   S_t = max(0, S_{t-1} + (MD_t - k))
 *   Alarm if S_t > H
 *
 * The slack 'k' reduces sensitivity to noise (nominal variance).
 * When MD > k, evidence accumulates; when MD < k, S decays toward 0.
 */
uint8_t cusum_update(cusum_state_t *state,
                     const uint32_t obs[3],
                     uint32_t cp_id) {
    /* Already alarmed? Don't update further */
    if (state->alarm) {
        return 1;
    }

    /* A sub-stage far above its normal range is an alarm by itself. This also
     * covers values the distance arithmetic cannot represent. */
    for (int i = 0; i < 3; i++) {
        if (obs[i] > SUBSTAGE_ALARM_CYCLES) {
            state->alarm = 1;
            state->alarm_cp = cp_id;
            return 1;
        }
    }

    /* Compute Mahalanobis distance for this observation */
    fixed_t md = mahalanobis_distance(obs, &CUSUM_MODEL);

    /* Update CUSUM statistic: S = max(0, S + MD - k) */
    fixed_t increment = md - CUSUM_MODEL.k_slack;
    state->S = state->S + increment;
    if (state->S < 0) {
        state->S = 0;  /* Clamp to 0 */
    }

    /* Check alarm condition */
    if (state->S > CUSUM_MODEL.H) {
        state->alarm = 1;
        state->alarm_cp = cp_id;
        return 1;  /* Attack detected! */
    }

    return 0;  /* No alarm */
}
