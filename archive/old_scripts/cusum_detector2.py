"""
cusum_detector2.py
=================
Loads the fitted model and tests it against the EMPIRICAL attack data
generated by the firmware (make collect-attack).
"""

import numpy as np
import pandas as pd
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import os

os.makedirs('results', exist_ok=True)

# 1. LOAD MODEL
m       = np.load('data/model.npz')
mu      = m['mu']
cov_inv = m['cov_inv']
K_SLACK = float(m['K_SLACK'])
H_99    = float(m['H_99'])

print(f"Model loaded. Threshold H_99 = {H_99:.4f}, Slack k = {K_SLACK:.4f}")

# 2. LOAD EMPIRICAL DATA (Nominal + Attack)
print("Loading firmware data...")
df_att = pd.read_csv('data/attack_boots.csv')

# Use the pre-cleaned nominal data directly from the saved model
X_nom = m['X'] 

# Extract CP2 features for the attack data
X_att = df_att[df_att['cp'] == 2][['sub_a', 'sub_b', 'sub_c']].values.astype(float)

# Create a continuous stream: 100 clean boots followed by the attacked boots
N_CLEAN = 100
stream = np.vstack([X_nom[:N_CLEAN], X_att])

# 3. RUN CUSUM
S_trace  = np.zeros(len(stream))
MD_trace = np.zeros(len(stream))
s        = 0.0
alarm_idx = -1

for i, x in enumerate(stream):
    d = x - mu
    md = float(np.sqrt(d @ cov_inv @ d))
    s = max(0.0, s + md - K_SLACK)
    
    S_trace[i]  = s
    MD_trace[i] = md
    
    if s > H_99 and alarm_idx == -1:
        alarm_idx = i

# 4. RESULTS & PLOTTING
print(f"\n=== DETECTION RESULTS ===")
if alarm_idx == -1:
    print("✗ NO ALARM TRIGGERED. The glitch was absorbed by QEMU jitter.")
elif alarm_idx < N_CLEAN:
    print(f"⚠ FALSE ALARM triggered during clean boot {alarm_idx}.")
else:
    lag = alarm_idx - N_CLEAN
    print(f"✓ ALARM SUCCESSFULLY TRIGGERED at boot {alarm_idx} (Lag: {lag} boots).")

fig, axes = plt.subplots(2, 1, figsize=(12, 8), sharex=True)
fig.suptitle('CUSUM Detector on Empirical Firmware Attack', fontsize=14)

# Plot 1: Sub_B Cycles
axes[0].plot(stream[:, 1], 'b-', alpha=0.7, label='sub_b (Key Reduction) Cycles')
axes[0].axvline(N_CLEAN, color='red', ls='--', lw=2, label='Firmware Attack Starts')
axes[0].axhline(mu[1], color='green', ls=':', label=f'Nominal Mean ({mu[1]:.0f})')
axes[0].set_ylabel('Cycles')
axes[0].legend()
axes[0].grid(True, alpha=0.3)

# Plot 2: CUSUM Score
axes[1].plot(S_trace, color='purple', lw=2, label='CUSUM Score (S)')
axes[1].axvline(N_CLEAN, color='red', ls='--', lw=2)
axes[1].axhline(H_99, color='orange', ls='--', lw=2, label=f'Alarm Threshold (H_99={H_99:.1f})')
if alarm_idx != -1:
    axes[1].scatter(alarm_idx, S_trace[alarm_idx], color='red', s=100, zorder=5, label='DETECTION')
axes[1].set_xlabel('Boot Sequence Index')
axes[1].set_ylabel('CUSUM Score')
axes[1].legend()
axes[1].grid(True, alpha=0.3)

plt.tight_layout()
plt.savefig('results/empirical_attack.png', dpi=150)
print("\nSaved trace to results/empirical_attack.png")